import math

puntaje_bienestar = 81

print("Raíz cuadrada del puntaje de bienestar:")
print(math.sqrt(puntaje_bienestar))

promedio_emocional = 3.2
print("Redondeo hacia arriba del promedio emocional:")
print(math.ceil(promedio_emocional))

nivel_ansiedad = 3.8
print("Redondeo hacia abajo del nivel de ansiedad:")
print(math.floor(nivel_ansiedad))

indice_estabilidad = 3.555552
print("Índice de estabilidad emocional redondeado a 2 decimales:")
print(round(indice_estabilidad, 2))